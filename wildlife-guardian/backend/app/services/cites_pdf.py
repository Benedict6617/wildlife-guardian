"""
Generates a CITES-style permit/certificate PDF from a CITESPermit record.

Field layout follows the standard CITES permit/certificate form structure
(exporter/importer, species description, purpose code, quantity) as a
practical starting template. This is a documentation aid for conservancy
paperwork, not a legally issued government instrument -- real permits are
only valid when issued through each country's CITES Management Authority.
"""
from fpdf import FPDF

from app import models

PURPOSE_CODES = {
    "scientific": "N - Scientific",
    "translocation": "T - Translocation (conservation)",
    "seizure_disposal": "I - Confiscated/seized specimen disposal",
    "captive_bred": "C - Captive bred",
}


class _PermitPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 13)
        self.cell(0, 8, "CITES TRADE DOCUMENTATION", ln=True, align="C")
        self.set_font("Helvetica", "", 9)
        self.cell(0, 5, "Convention on International Trade in Endangered Species", ln=True, align="C")
        self.ln(4)
        self.set_draw_color(60, 60, 60)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        self.cell(0, 8, "Generated by Wildlife Guardian Platform - not valid without Management Authority signature", align="C")


def _row(pdf: _PermitPDF, label: str, value: str):
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(55, 7, label, border=0)
    pdf.set_font("Helvetica", "", 10)
    pdf.multi_cell(0, 7, value or "-")


def generate_permit_pdf(permit: models.CITESPermit, species: models.Species, output_path: str) -> str:
    pdf = _PermitPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    _row(pdf, "Permit Number:", permit.permit_number)
    _row(pdf, "Status:", permit.status.upper() if isinstance(permit.status, str) else str(permit.status.value).upper())
    _row(pdf, "Issuing Authority:", permit.issuing_authority)
    _row(pdf, "Issue Date:", permit.issue_date.strftime("%d %b %Y"))
    _row(pdf, "Expiry Date:", permit.expiry_date.strftime("%d %b %Y") if permit.expiry_date else "N/A")
    pdf.ln(3)

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Species Description", ln=True)
    pdf.set_draw_color(200, 200, 200)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(2)
    _row(pdf, "Common Name:", species.common_name)
    _row(pdf, "Scientific Name:", species.scientific_name)
    _row(pdf, "CITES Appendix:", species.cites_appendix or "N/A")
    _row(pdf, "Conservation Status:", species.conservation_status.replace("_", " ").title()
         if isinstance(species.conservation_status, str) else str(species.conservation_status.value).replace("_", " ").title())
    pdf.ln(3)

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Transaction Details", ln=True)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(2)
    _row(pdf, "Purpose:", PURPOSE_CODES.get(permit.purpose, permit.purpose))
    _row(pdf, "Quantity:", f"{permit.quantity} x {permit.unit_description}")
    _row(pdf, "Origin Country:", permit.origin_country)
    _row(pdf, "Destination Country:", permit.destination_country)
    if permit.notes:
        _row(pdf, "Notes:", permit.notes)

    pdf.ln(15)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(90, 7, "_______________________________", ln=0)
    pdf.cell(0, 7, "_______________________________", ln=1)
    pdf.cell(90, 6, "Management Authority Signature", ln=0)
    pdf.cell(0, 6, "Date", ln=1)

    pdf.output(output_path)
    return output_path
